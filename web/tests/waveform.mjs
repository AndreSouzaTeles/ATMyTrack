import assert from 'node:assert/strict';
import {peakEnvelope,projectEnvelope} from '../dist/waveform.js';
const rate=48000,n=rate*4,left=new Float32Array(n),right=new Float32Array(n);
for(let i=0;i<n;i++)if(i<rate||i>=rate*2)right[i]=.4*Math.sin(2*Math.PI*220*i/rate);
const peaks=peakEnvelope([left,right]);
assert.equal(peaks.length,2048);
assert.ok(peaks.slice(0,512).every(v=>v>.25&&v<.31));
assert.ok(peaks.slice(512,1024).every(v=>v===0));
assert.ok(peaks.slice(1024).every(v=>v>.25&&v<.31));
assert.deepEqual(projectEnvelope([{duration:4,peaks}]),peaks);
const combined=projectEnvelope([{duration:4,peaks:peakEnvelope([left])},{duration:4,peaks}]);
for(let i=0;i<peaks.length;i++)assert.ok(Math.abs(combined[i]-peaks[i]/Math.sqrt(2))<1e-9);
const impulse=new Float32Array(n);impulse[12345]=.7;
const transient=peakEnvelope([impulse]);assert.equal(transient.filter(v=>v>0).length,1);assert.ok(Math.max(...transient)<.1);
assert.ok(peakEnvelope([new Float32Array(0)]).every(v=>v===0));
console.log('RMS2048 waveform: stereo, silence, energy aggregate and transient passed');
